// Función para validar automáticamente si la palabra existe en la base
function validarConDiccionario(categoria, letra, palabra) {
    const cleanWord = palabra.trim().toUpperCase();
    if (diccionarioTuttiFrutti[categoria] && diccionarioTuttiFrutti[categoria][letra]) {
        return diccionarioTuttiFrutti[categoria][letra].includes(cleanWord);
    }
    return false; // Retorna falso si no está registrada todavía
}